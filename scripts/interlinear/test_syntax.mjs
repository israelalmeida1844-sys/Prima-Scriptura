import {chromium} from "playwright";
import fs from "node:fs";
import assert from "node:assert/strict";
const read=p=>JSON.parse(fs.readFileSync(p,"utf8"));
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:390,height:844}});
const errors=[];page.on("pageerror",e=>errors.push(String(e)));
const checks=[];
try{
  await page.goto("http://127.0.0.1:4321/interlinear-experimental/");
  await page.locator("#words article").first().waitFor();
  await page.locator("#book").selectOption("Gen");
  await page.waitForFunction(()=>document.querySelector("#chapter").value==="1"&&document.querySelector("#verse").value==="1"&&document.querySelectorAll("#words article").length===7);
  await page.locator("#syntax-open").click();
  await page.locator("#syntax-coverage").waitFor();
  assert.match(await page.locator("#syntax-coverage").innerText(),/^7 de 7 /);
  assert.ok(await page.locator("#syntax-content strong").filter({hasText:"Objeto"}).count()>0);
  assert.ok(await page.locator("#syntax-content button").filter({hasText:"Sujeito"}).count()>0);
  checks.push("genesis_constituents");
  await page.locator('#words article[data-token-index="1"]').getByRole("button",{name:"Sintaxe",exact:true}).click();
  await page.locator("#syntax-content h3").waitFor();
  assert.match(await page.locator("#syntax-content").innerText(),/Verbo \[v\]/);
  assert.ok(await page.locator(".syntax-selected").count()>0);checks.push("selected_word_path");
  await page.locator("#verse").selectOption("2");
  assert.equal(await page.locator("#syntax-content").innerText(),"");checks.push("stale_tree_cleared");
  await page.locator("#book").selectOption("3John");
  await page.waitForFunction(()=>document.querySelector("#book").value==="3John"&&document.querySelector("#verse").value==="1"&&document.querySelector("#words article .original")?.textContent?.includes("Ὁ"));
  await page.locator("#syntax-open").click();await page.locator("#syntax-coverage").waitFor();
  const j=read("public/interlinear-syntax/3John/1.json")["1:1"];
  assert.match(await page.locator("#syntax-coverage").innerText(),new RegExp("^"+j.matched+" de "));
  assert.ok(await page.locator("#syntax-content").getByText(/Objeto indireto/).count()>0);checks.push("greek_tree");
  await page.locator("#book").selectOption("Dan");
  await page.waitForFunction(()=>document.querySelector("#chapter option[value='7']")!==null);
  await page.locator("#chapter").selectOption("7");
  await page.locator("#verse").selectOption("1");
  await page.locator("#syntax-open").click();await page.locator("#syntax-coverage").waitFor();
  const d=read("public/interlinear-syntax/Dan/7.json")["7:1"];
  assert.match(await page.locator("#syntax-coverage").innerText(),new RegExp("^"+d.matched+" de "));
  assert.ok(await page.locator("#syntax-content button").count()>0);checks.push("aramaic_tree");
  await page.locator("#syntax-content button").first().click();
  await page.locator("#syntax-content h3").waitFor();checks.push("tree_to_token");
  assert.deepEqual(errors,[]);
  fs.writeFileSync("docs/testes-sintaxe-navegador.json",JSON.stringify({status:"passed",viewport:[390,844],checks,page_errors:errors},null,2)+"\n");
  console.log("Syntax checks:",checks.join(", "));
}finally{await browser.close();}
