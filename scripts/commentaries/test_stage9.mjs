import {chromium} from "playwright";
import fs from "node:fs";
import assert from "node:assert/strict";
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:390,height:844}});
const errors=[];page.on("pageerror",e=>errors.push(String(e)));
const checks=[];
try{
 await page.goto("http://127.0.0.1:4321/interlinear-experimental/");
 await page.locator("#words article").first().waitFor();
 await page.locator('#comment-author option[value="MHC"]').waitFor({state:"attached"});
 await page.locator("#comment-author").selectOption("MHC");
 await page.locator("#comment-open").click();
 await page.locator("#comment-content .commentary-original").waitFor();
 assert.ok((await page.locator("#comment-content .commentary-original").textContent()).trim().length>20);
 assert.match(await page.locator("#comment-content").textContent(),/KJV/);
 checks.push("henry_original");
 await page.locator("#comment-author").selectOption("JFB");
 await page.locator("#comment-open").click();
 await page.locator("#comment-content .commentary-original").waitFor();
 checks.push("jfb_original");
 await page.locator("#comment-author").selectOption("");
 await page.locator("#comment-open").click();
 await page.waitForFunction(()=>document.querySelectorAll("#comment-content .commentary-entry").length===6);
 checks.push("comparison");
 await page.locator("#comment-lang").selectOption("pt");
 await page.locator("#comment-open").click();
 await page.locator("#comment-content").getByText("Tradução revisada em português ainda não disponível. Selecione o original em inglês.").first().waitFor();
 checks.push("translation_not_fabricated");
 await page.locator("#exegesis-open").click();
 await page.locator("#exegesis-content").getByText("Nenhuma nota editorial homologada nesta referência.").waitFor();
 checks.push("editorial_not_fabricated");
 await page.locator("#book").selectOption("1John");
 await page.waitForFunction(()=>document.querySelector("#chapter option[value='5']"));
 await page.locator("#chapter").selectOption("1");
 await page.locator("#verse").selectOption("3");
 await page.locator("#criticism-open").click();
 await page.locator("#criticism-content").getByText(/καὶ WH Treg NA28/).waitFor();
 checks.push("greek_apparatus");
 const font=await page.locator("#criticism-content p").first().evaluate(e=>getComputedStyle(e).fontFamily);
 assert.match(font,/Times New Roman/);
 checks.push("font_css");
 await page.locator("#book").selectOption("Gen");
 await page.waitForFunction(()=>document.querySelector("#chapter option[value='50']"));
 await page.locator("#chapter").selectOption("8");
 await page.locator("#verse").selectOption("17");
 await page.locator("#criticism-open").click();
 await page.locator("#criticism-content details").first().waitFor();
 checks.push("hebrew_source_notes");
 assert.deepEqual(errors,[]);
 fs.writeFileSync("docs/testes-etapa-9.json",JSON.stringify({status:"passed",checks,page_errors:errors,font_css:font},null,2)+"\n");
}finally{await browser.close();}
